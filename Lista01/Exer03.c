#include <stdio.h> /* Isso serve para o printf*/

int main() { /* Função para abrir o programa*/

    char nome[] = "Luísa"; /* Declaração da variável e agregando valor a variável*/

    printf("Meu nome é %s", nome); /* função printf para exibição de saída no terminal*/

    getchar(); /* Essa função serve para que o programa fique aberto até que, após os blocos serem realizados, a pessoa aperte uma tecla qualquer para encerrar*/
    return 0; /* Função para fechar o programa*/

}